import json, re, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ns = {}
for f in ('translations.py', 'translations_content.py', 'translations_extra.py'):
    exec(open(os.path.join(HERE, f), encoding='utf-8').read(), ns)
T = ns['T']
codes = ['ml', 'hi', 'fr', 'de', 'ar']
xc = ['es', 'zh', 'ja', 'pt']
X = ns['X']
out = {c: {} for c in codes + xc}
for en, tup in X.items():
    for c, v in zip(xc, tup): out[c][en] = v
for en, tup in T.items():
    assert len(tup) == 5, en
    for c, v in zip(codes, tup): out[c][en] = v
js = '/* Generated by build_i18n.py from translations.py. Keys are the exact English strings used on the pages. */\nwindow.I18N = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n'
open(os.path.join(ROOT, 'i18n.js'), 'w', encoding='utf-8').write(js)
print(len(T), 'entries')
